import os
from typing import Union, Tuple

import lzytools
import natsort

TEMP_EXTRACT_FOLDER = 'UnzipTempFolder'  # ?????????


def is_exists_temp_folder(paths: Union[list, str]) -> Tuple[bool, Union[str, None]]:
    """???????????????????????"""
    temp_folders = _create_temp_folder_path(paths)

    # ???????????
    for path in temp_folders:
        if os.path.exists(path) and lzytools.file.get_size(path):  # ???????
            print('???????????', path, os.listdir(path))
            return True, path

    return False, None


def delete_temp_folder(paths: Union[list, str]):
    """??????????????????????"""
    temp_folders = _create_temp_folder_path(paths)

    # ???????????
    for path in temp_folders:
        if os.path.exists(path):
            os.remove(path)


def _create_temp_folder_path(paths: Union[list, str]) -> list:
    """?????????????????????????(?????,????)
    :return: ?????????"""
    # ????
    if isinstance(paths, str):
        paths = [paths]

    # ?????????????(?????????,???????)
    temp_folders = set()
    for path in paths:
        if os.path.isfile(path):
            dirpath = os.path.dirname(path)
            # ????(?????)???????
            safe_name = os.path.splitext(os.path.basename(path))[0]
            for ch in ['\\', '/', ':', '*', '?', '"', '<', '>', '|']:
                safe_name = safe_name.replace(ch, '_')
            temp_name = f'{safe_name}_{TEMP_EXTRACT_FOLDER}'
            join_path = os.path.join(dirpath, temp_name)
            temp_folders.add(join_path)
        else:
            join_path = os.path.join(path, TEMP_EXTRACT_FOLDER)
            temp_folders.add(join_path)

    # ????
    temp_folders = natsort.os_sorted(temp_folders)

    return temp_folders
